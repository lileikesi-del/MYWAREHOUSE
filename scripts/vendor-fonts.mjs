// One-off migration helper: turn the fonts that `next/font/google` inlined into
// the last build output into repo-owned assets, so `next build` no longer needs
// to reach fonts.googleapis.com (unreachable from mainland China build hosts).
//
//   node scripts/vendor-fonts.mjs
//
// Writes public/fonts/*.woff2 and src/app/fonts.css. Run it once against a
// build that was produced on a machine with Google access; afterwards layout.tsx
// imports fonts.css and the @font-face rules serve from /fonts/.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const cssDir = path.join(root, ".next/static/css");
const mediaDir = path.join(root, ".next/static/media");
const outFonts = path.join(root, "public/fonts");
const outCss = path.join(root, "src/app/fonts.css");

if (!existsSync(cssDir)) {
  console.error("没有 .next/static/css，先跑一次 next build（在有 Google 网络的机器上）");
  process.exit(1);
}

const css = readdirSync(cssDir)
  .filter((f) => f.endsWith(".css"))
  .map((f) => readFileSync(path.join(cssDir, f), "utf8"))
  .join("\n");

// Every @font-face block that points at a Next-hashed woff2.
const faces = css.match(/@font-face\{[^}]*_next\/static\/media\/[^}]*\}/g) ?? [];
if (faces.length === 0) {
  console.error("构建产物里没有找到 @font-face，可能字体没被内联");
  process.exit(1);
}

mkdirSync(outFonts, { recursive: true });
const copied = new Set();
const rewritten = faces.map((block) => {
  return block.replace(/\/_next\/static\/media\/([A-Za-z0-9-]+\.woff2)/g, (_m, name) => {
    if (!copied.has(name)) {
      const src = path.join(mediaDir, name);
      if (!existsSync(src)) throw new Error(`缺少字体文件 ${name}`);
      copyFileSync(src, path.join(outFonts, name));
      copied.add(name);
    }
    return `/fonts/${name}`;
  });
});

// The CSS variable names layout.tsx used to get from next/font.
const vars = [".__variable_d8ebd1", ".__variable_74ee37", ".__variable_f1382c"].map((sel) => {
  const m = css.match(new RegExp(`\\${sel}\\{([^}]*)\\}`));
  return m?.[1] ?? null;
});
if (vars.some((v) => v === null)) {
  console.error("没找到字体变量的定义，选择器可能变了，检查 .next/static/css");
  process.exit(1);
}

const header = `/* Self-hosted fonts, generated by scripts/vendor-fonts.mjs.
   The files live in public/fonts and are served from /fonts/.
   Regenerate only if the font families or weights change. */
:root{${vars.join(";")}}
`;

writeFileSync(outCss, `${header}${rewritten.join("\n")}\n`);
console.log(`@font-face: ${faces.length}, 字体文件: ${copied.size}`);
console.log(`写入 ${path.relative(root, outCss)} 和 ${path.relative(root, outFonts)}/`);
